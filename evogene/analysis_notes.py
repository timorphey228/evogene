def annotations_for_report(report):
    events = report.get("pipeline_events") or []
    states = {}
    for event in events:
        if event.get("stage") and event.get("state") != "running":
            states.setdefault(event["stage"], []).append(event["state"])
    case = report.get("input_type") == "published_preselected_hits_not_whole_genome_or_msa"
    result = []
    for note in ANNOTATIONS:
        key = note["key"]
        if key.startswith("case_") and not case:
            continue
        if case and key in {
            "download", "dna_alignment", "cds_annotation", "target_reference",
            "target_mapping", "gene_structure", "protein_homology", "synteny",
            "orf", "cigar", "mechanism_tests",
        }:
            continue
        if key == "input" and case:
            state = "preselected_data"
        elif key.startswith("case_"):
            state = "available_in_file" if report.get("method_comparison") else "not_assessed"
        elif key == "phylogeny":
            state = (report.get("phylogeny") or {}).get("status", "not_assessed")
        elif key == "orf":
            state = "surveyed" if "query_orfs" in report else "not_assessed"
        elif key == "cigar":
            has_cigar = any(h.get("alignment_insertion_nt") is not None for hs in
                            (report.get("relatives") or {}).values() for h in hs)
            state = "observed" if has_cigar else "not_assessed"
        else:
            statuses = states.get(key, [])
            state = ("failed" if "failed" in statuses else
                     "completed" if "completed" in statuses else
                     "skipped" if "skipped" in statuses else "not_assessed")
        result.append({**note, "state": state})
    return result


def render_analysis_annotations(report):
    import streamlit as st
    st.header("Аннотация к каждому этапу анализа")
    st.caption("Выполненный вычислительный этап отделён от научной интерпретации. "
               "«Не оценено» не равно «признак отсутствует».")
    notes = annotations_for_report(report)
    st.dataframe([
        {"Этап": item["title"], "Состояние": item["state"],
         "Научный вопрос": item["question"]}
        for item in notes
    ], use_container_width=True, hide_index=True)
    choice = st.selectbox("Подробная методическая аннотация",
                          options=range(len(notes)),
                          format_func=lambda i: notes[i]["title"],
                          key="evo_analysis_stage_note")
    item = notes[choice]
    st.markdown("**Научный вопрос:** " + item["question"])
    st.markdown("**Метод/источник:** " + item["method"])
    st.markdown("**Что показывает результат:** " + item["meaning"])
    st.markdown("**Что из результата НЕ следует:** " + item["limitation"])
    st.markdown("**Визуализация:** " + item["visual"])
